def build_knife(path):
    o = Obj()
    # handle at origin, blade forward
    o.box("dark",   0, 0, 0.055, 0.030, 0.030, 0.11)
    o.box("silver", 0, 0.004, 0.19, 0.012, 0.045, 0.22)
    o.write(path)

def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    for gid, params in GUNS.items():
        path = os.path.join(OUT_DIR, gid + ".obj")
        if gid == "knife":
            build_knife(path)
        else:
            build_gun(params).write(path)
        print("wrote", os.path.relpath(path, os.path.join(OUT_DIR, "..", "..")))
    print("done: %d models in %s" % (len(GUNS), OUT_DIR))

if __name__ == "__main__":
    main()
