#!/usr/bin/env python3
"""
gen_guns.py - procedural gun model generator for Dead Arrival.

Builds every gun's viewmodel from parameters (receiver, barrel, mag type,
stock, sights, ...) and exports OBJ + MTL to assets/guns/<id>.obj.

Conventions (see tools/README.md):
  - origin at the grip, +Z forward (muzzle), +Y up, +X right, meters
  - parts colored via materials named  body / dark / accent / silver
    (the game tints these per skin; base colors approximate the old look)
  - regenerate everything with:  python3 tools/gen_guns.py
"""
import math
import os

OUT_DIR = os.path.join(os.path.dirname(__file__), "..", "assets", "guns")

# ---------------------------------------------------------------------------
# Tiny OBJ builder: axis-aligned boxes (the game's whole visual language)
# ---------------------------------------------------------------------------
class Obj:
    def __init__(self):
        self.v = []       # vertices
        self.faces = []   # (mat, [4 vertex indices])
        self.mats = []    # material names in order of first use

    def box(self, mat, cx, cy, cz, sx, sy, sz):
        """Axis-aligned box centered at (cx,cy,cz) with size (sx,sy,sz)."""
        if mat not in self.mats:
            self.mats.append(mat)
        x0, x1 = cx - sx / 2, cx + sx / 2
        y0, y1 = cy - sy / 2, cy + sy / 2
        z0, z1 = cz - sz / 2, cz + sz / 2
        base = len(self.v)
        # 8 corners
        self.v += [
            (x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
            (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1),
        ]
        for quad in ((1, 2, 6, 5), (4, 7, 3, 0),   # -Z +Z
                     (0, 3, 7, 4), (2, 3, 7, 6),   # -X +X (wound consistently)
                     (0, 1, 5, 4), (5, 6, 7, 4)):  # -Y +Y-ish tops
            self.faces.append((mat, [base + q - 1 for q in quad]))

    def write(self, path):
        with open(path, "w") as f:
            f.write("# Dead Arrival gun model (generated by tools/gen_guns.py)\n")
            f.write("mtllib %s.mtl\n" % os.path.basename(path)[:-4])
            for (x, y, z) in self.v:
                f.write("v %.4f %.4f %.4f\n" % (x, y, z))
            for mat in self.mats:
                f.write("usemtl %s\n" % mat)
                for (m, quad) in self.faces:
                    if m == mat:
                        f.write("f " + " ".join(str(i + 1) for i in quad) + "\n")
        # companion MTL with the base colors (the game applies skins on top)
        with open(path[:-4] + ".mtl", "w") as f:
            f.write("# generated\n")
            for mat, (r, g, b) in (
                ("body",   ( 52,  54,  58)),
                ("dark",   ( 34,  35,  38)),
                ("accent", (110,  85,  60)),
                ("silver", (200, 202, 208)),
            ):
                f.write("newmtl %s\nKd %.3f %.3f %.3f\nKa 0 0 0\nKs 0.1 0.1 0.1\nNs 10\n\n"
                        % (mat, r / 255, g / 255, b / 255))

# ---------------------------------------------------------------------------
# Parameterized gun builder
# ---------------------------------------------------------------------------
def build_gun(p):
    """p: dict of parameters -> Obj. All sizes in meters, gun-space."""
    o = Obj()
    L = p["len"]          # receiver length
    W = p["width"]        # receiver width
    H = p["height"]       # receiver height
    bl = p["barrel_len"]  # barrel length
    br = p["barrel_r"]    # barrel radius (approx as box half-extent)
    grip = p.get("grip", 0.09)
    # receiver: ahead of the grip origin, top just above y=0
    o.box("body", 0, 0.01, L * 0.5, W, H, L)
    # barrel
    o.box("dark", 0, H * 0.25, L + bl * 0.5, br * 2, br * 2, bl)
    # sights
    sh = p.get("sight_h", 0.05)
    if p.get("sights", True):
        o.box("dark", 0, H * 0.5 + sh * 0.5, L + bl * 0.92, 0.012, sh, 0.014)
        o.box("dark", 0, H * 0.5 + sh * 0.4, 0.02, 0.030, sh * 0.6, 0.012)
    # grip (origin)
    o.box("accent", 0, -grip * 0.55, L * 0.16, 0.032, grip, 0.042)
    # magazine
    mag_t = p.get("mag", "box")     # box | banana | drum | tube | none | bullpup
    mw, mh = p.get("mag_w", 0.045), p.get("mag_h", 0.16)
    if mag_t == "box" and mh > 0:
        o.box("accent", 0, -mh * 0.5 - 0.01, L * 0.42, mw, mh, mw * 2.2)
    elif mag_t == "banana":
        o.box("accent", 0, -mh * 0.5 - 0.01, L * 0.42, mw, mh, mw * 2.2)
        o.box("accent", 0.008, -mh * 0.5 - 0.05, L * 0.42 + 0.045, mw * 0.9, mh * 0.75, mw * 2.0)
        o.box("accent", 0, H * 0.28, L + bl * 0.3, 0.052, 0.048, bl * 0.3)  # handguard
    elif mag_t == "drum":
        o.box("dark", 0, -mh * 0.5 - 0.055, L * 0.4, 0.10, 0.085, 0.115)
        o.box("dark",  0.028, H * 0.3, L + bl * 0.55, 0.012, 0.012, bl * 0.3)  # bipod
        o.box("dark", -0.028, H * 0.3, L + bl * 0.55, 0.012, 0.012, bl * 0.3)
    elif mag_t == "bullpup":
        o.box("accent", 0, -0.055, -L * 0.22, 0.044, 0.15, 0.058)
    # stock
    st = p.get("stock", 0.0)
    if st > 0:
        o.box("accent", 0, -0.01, -st * 0.5 + 0.01, 0.036, 0.062, st)
    if p.get("fold_stock"):
        o.box("dark", 0, H * 0.45, -st * 0.5 - 0.02, 0.020, 0.018, st * 0.8)
        o.box("accent", 0, -0.065, L * 0.72, 0.024, 0.07, 0.030)  # foregrip
    # per-family extras
    if p.get("revolver"):
        o.box("dark", 0, -0.012, L * 0.55, 0.055, 0.055, 0.055)               # cylinder
        o.box("dark", 0, H * 0.5 + 0.008, L * 0.6 + bl * 0.25, 0.014, 0.012, bl * 0.5)
    if p.get("wings"):
        o.box("dark",  0.03, H * 0.25, L + bl * 0.5, 0.010, 0.034, bl * 0.8)
        o.box("dark", -0.03, H * 0.25, L + bl * 0.5, 0.010, 0.034, bl * 0.8)
        o.box("dark", 0, H * 0.5 + 0.012, L * 0.3, 0.016, 0.014, 0.06)
    if p.get("double_barrel"):
        o.box("dark",  0.019, H * 0.25, L + bl * 0.5, br * 1.7, br * 1.7, bl)
        o.box("dark", -0.019, H * 0.25, L + bl * 0.5, br * 1.7, br * 1.7, bl)
        o.box("silver", 0, 0, L * 0.85, 0.058, 0.045, 0.03)
    if p.get("tube_mag"):
        o.box("dark", 0, -H * 0.42, L + bl * 0.45, 0.036, 0.036, bl * 0.7)
        o.box("accent", 0, -H * 0.42, L + bl * 0.15, 0.046, 0.02, 0.03)
    if p.get("underslung"):
        o.box("dark", 0, -H * 0.5, L + bl * 0.4, 0.062, 0.062, bl * 0.62)
    if p.get("carry_handle"):
        o.box("dark", 0, H * 0.5 + 0.035, L * 0.5, 0.020, 0.026, L * 0.55)
        o.box("dark", 0, H * 0.35 + sh * 0.5, L + bl * 0.8, 0.026, sh, 0.026)
    if p.get("bullpup_shell"):
        o.box("dark", 0, H * 0.5, -L * 0.25, 0.030, 0.02, L * 0.3)            # cheek riser
        o.box("dark", 0, -0.07, L * 0.55, 0.022, 0.075, 0.028)                # fwd grip
    if p.get("bolt_sniper"):
        o.box("dark", 0.05, H * 0.2, L * 0.35, 0.05, 0.012, 0.012)            # bolt handle
        o.box("dark", 0, H * 0.5 + 0.005, L * 0.30, 0.032, 0.02, 0.024)      # scope rings
        o.box("dark", 0, H * 0.5 + 0.005, L * 0.68, 0.032, 0.02, 0.024)
    if p.get("scope"):
        o.box("dark", 0, H * 0.55 + 0.03, L * 0.5, 0.026, 0.026, 0.16)
    if p.get("pump"):
        o.box("accent", 0, H * 0.1, L + bl * 0.35, 0.045, 0.038, 0.13)
    return o

